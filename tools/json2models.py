#!/usr/bin/env python3
"""Merge the JSON batches exported by tools/zov_lib.py (Blender) into src/models.js"""
import json, sys, os, glob
here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, 'assets')
models = {}
for fn in sorted(glob.glob(os.path.join(src, '*.json'))):
    if os.path.basename(fn) == 'test.json': continue
    models.update(json.load(open(fn)))
out = os.path.join(here, '..', 'src', 'models.js')
with open(out, 'w') as f:
    f.write('// generated by tools/json2models.py from Blender exports (tools/zov_lib.py) — do not edit by hand\n')
    f.write('const MODELS=' + json.dumps(models, separators=(',', ':'), ensure_ascii=False) + ';\n')
print(len(models), 'models ->', out, os.path.getsize(out), 'bytes')
